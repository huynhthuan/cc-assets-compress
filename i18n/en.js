function flatten(map, prefix = '', output = {}) {
    for (const [key, value] of Object.entries(map)) {
        const fullKey = prefix ? `${prefix}.${key}` : key;
        if (typeof value === 'object') {
            flatten(value, fullKey, output);
        } else {
            output[fullKey] = value;
        }
    }
    return output;
}

